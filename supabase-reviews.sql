-- TECNOSHIELD website reviews: public submissions require approval before display.
create table if not exists public.website_reviews (
  id bigint generated by default as identity primary key,
  display_name text not null check (char_length(btrim(display_name)) between 2 and 50),
  service text not null check (service in (
    'Dispositivos móviles',
    'Computación',
    'Conectividad',
    'Videovigilancia',
    'Protección digital',
    'Soporte empresarial',
    'Soluciones para condominios',
    'Suministro de materiales y equipos'
  )),
  rating smallint not null check (rating between 1 and 5),
  review_text text not null check (char_length(btrim(review_text)) between 20 and 1200),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

alter table public.website_reviews enable row level security;

drop policy if exists "Anyone can read approved reviews" on public.website_reviews;
create policy "Anyone can read approved reviews"
  on public.website_reviews for select to anon, authenticated
  using (status = 'approved');

drop policy if exists "Visitors can submit pending reviews" on public.website_reviews;
create policy "Visitors can submit pending reviews"
  on public.website_reviews for insert to anon, authenticated
  with check (status = 'pending');

grant select, insert on public.website_reviews to anon, authenticated;
grant usage, select on sequence public.website_reviews_id_seq to anon, authenticated;

-- Add the table to Supabase Realtime only if it is not already published.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'website_reviews'
  ) then
    alter publication supabase_realtime add table public.website_reviews;
  end if;
end $$;

